    /** code → intitulé, trié par code. */
    public static synchronized Map<String, String> all() {
        if (map == null) {
            java.util.TreeMap<String, String> t = new java.util.TreeMap<>();
            for (String l : RAW.split("\n")) {
                int i = l.indexOf('|');
                if (i > 0) t.put(l.substring(0, i), l.substring(i + 1));
            }
            map = new LinkedHashMap<>(t);
        }
        return map;
    }
